/**
 * 『下ばっか見てると』v1.0 — 数字と曲線の全部。
 *
 * v0.13 までの見下ろし版とは別物。骨格から作り直してある
 * （旧版は v0.13-topdown-keep ブランチに残してある）。
 *
 * 遊びの芯はひとつだけ:
 *
 *   **前を見るか、下を見るか。指がやることはそれだけ。**
 *
 *   下を見ている → 足元のフンを跨げる。でも前から来る鹿が見えない。しかも遅い
 *   前を見ている → 鹿をよけられる。速く走れる。でも足元を踏む
 *
 * 位置合わせが一切無いのが肝。前の版は2軸のドラッグで、失敗が必ず
 * 「3px 左にいれば助かった」になり、そのぶん悔しかった。
 * ここでは失敗が「どっちを見るかを間違えた」にしかならない。
 */

// ---- 画面 ----

/**
 * 画面。縦長のドット絵1枚。**下段の操作パッドは無い**——
 * 押す/離すしか無いので、画面のどこを触ってもよく、
 * ゲーム画面を縦いっぱいに使える。速さの体感はほぼこれで決まる。
 */
export const VIEW = { w: 160, h: 288 } as const;

/** 上にHUD。数字は小さく、端に寄せる。 */
export const HUD_H = 14;
export const FIELD_H = VIEW.h - HUD_H;

/**
 * 仕切りの位置（FIELD_H に対する比）。
 *
 * **拡大縮小ではなく、切り取る量を変える。**
 * ドット絵を縦に潰すと一発で嘘くさくなるので、絵の大きさは常に同じまま、
 * 見えている範囲だけを増やす。見ている側が広く、明るい。
 */
export const SPLIT_AHEAD = 0.60;  // 前を見ているとき、上帯がこれだけ
export const SPLIT_DOWN = 0.32;
/** 仕切りが動く速さ[1/s]。速すぎると酔い、遅いと切り替えた気がしない。 */
export const SPLIT_SPEED = 9;

/**
 * 見ていない側にかぶせる暗幕の濃さ。
 *
 * **前は 0.55 で、鹿の形がはっきり読めた。それがこのゲームを壊していた。**
 * 「完全に見えないと当てずっぽうになって理不尽」という理屈で薄くしたのだが、
 * 読めるということは**下を向いたまま鹿を監視できる**ということで、
 * 下を向くコストが実質ゼロになる。実際、遊んだ人の攻略法は
 * 「基本ずっと押していて、鹿が来た時だけ離す」——フンがどうでもよくなっていた。
 *
 * 芯は「どっちも同時には見られない」なので、**見えてはいけない**。
 * 「フンに集中していたら急に鹿が来てびっくり」——その"急に"は、
 * 見えていなかったからこそ成立する。
 *
 * **合図も出さない。**一度は「しか」の予告を出したが、予告があれば
 * 下を向いたままで済んでしまい、結局同じことになる。
 * 前を見ている間だけ分かる、でいい。そのために鹿を遠くから見せる（下の視差）。
 */
export const DIM = 0.92;

/**
 * **前方は「遠く」。だからゆっくり流れる。**
 *
 * 今回いちばん大きい変更。前は鹿が足元と同じ速さで迫ってきて、
 * 着くまで 0.72〜1.15秒 しか無かった。**顔を上げて確かめる暇がそもそも無い。**
 * だから合図を出さざるを得ず、合図があるから下を向いたままで済んでいた——
 * 「ずっと押していて鹿が来た時だけ離す」の根っこはここだった。
 *
 * 前方の帯は遠景なので、視差でゆっくり流れるのが物理的にも正しい。
 * 0.3倍にすると鹿は **3.2〜5.2秒** 見える。
 * **顔を上げれば必ず気づけ、上げなければ気づけない。**だから合図が要らない。
 */
export const AHEAD_PARALLAX = 0.3;

// ---- 走る ----

/** 子どもの立ち位置（左から）。 */
export const KID_X = 30;

/**
 * 走る速さ[px/s]。**前を見ていると速い。**
 *
 * 下を向いて歩くと足が遅くなるのは実際そうで、
 * ここが「稼ぐには前を見たい／でも足元が怖い」という綱引きになる。
 * 追加のルールを一つも足さずに、risk と reward が生まれる。
 */
export function speedAhead(t: number): number {
  return 96 + 58 * (1 - Math.exp(-t / 40));
}
export const SLOW_FACTOR = 0.62;

/**
 * 転んでいるあいだ[s]。長いと苛立ち、短いと失敗が伝わらない。
 *
 * **鹿にぶつかったほうを長くしてある。**
 * フンと鹿が重なって出る場面（clashChance）では、どちらかを必ず食う。
 * 損得が同じだと、そこにプレイヤーの選ぶ余地が無く、ただ理不尽になる。
 * 鹿のほうが重いので、重なったら**前を見て、フンを踏むのが正解**——
 * つまり「下ばっか見てると（鹿にぶつかる）」がそのまま最適手になる。
 */
export const TRIP_POOP = 0.55;
export const TRIP_DEER = 0.95;

// ---- 出てくるもの ----

/**
 * 障害物が現れてから足元に届くまでの時間[s]。**これが公平さの本体。**
 *
 * 反応時間の下限を 0.45秒 とし、そこから逆算して間隔を決める。
 * 画面の右端から KID_X までの距離を、そのときの速さで割った値がこれ。
 * 足りなくなったら速さではなく**出現の間隔**を詰める（下の interval）。
 */
export const T_MIN = 0.45;

/**
 * **最初のうちは、教える。**
 *
 * 「何をやっているのかよくわからないまま終わった」——それは説明文の問題ではなく、
 * **初回に教える時間が無かった**から。この秒数のあいだは
 *   ・フンと鹿を交互に、ゆっくり、1つずつ出す
 *   ・重ねない
 *   ・踏んでも汚れない（転ぶ絵は出す。何が起きたかは見せる）
 * つまり**必ず1回ずつ、安全に体験させてから**本番に入る。
 */
export const INTRO_TIME = 11;

/**
 * 右端に出たものが足元に届くまでの時間[s]。
 * 速さが上がっても (VIEW.w - KID_X) / v なので、いちばん速い 120px/s でも
 * (128-26)/120 = 0.85秒。**T_MIN を割ることは構造的に起きない。**
 * だから難しくするときは速さではなく、下の間隔だけを詰めればいい。
 */
export function leadTime(t: number): number {
  return (VIEW.w - KID_X) / speedAhead(t);
}

/** 鹿が出てくる間隔[s]。奥へ行くほど詰まる。 */
export function deerInterval(t: number): number {
  return Math.max(2.8, 5.4 * Math.exp(-t / 70));
}

// ---- 汚れた区間（フンの置き方） ----

/**
 * **フンは点ではなく「区間」で来る。**
 *
 * 前は1粒ずつだったので、下を向くのが一瞬で済み、
 * **「集中する」という状態がそもそも生まれなかった**。
 * 石畳が何マスか続けて汚れていれば、そのあいだずっと下を見ることになる。
 * そのあいだ前は見えない。これが「フンを避けることに集中している」の中身。
 *
 * 汚れた区間のあいだにはきれいな区間があり、そこが**顔を上げる隙**になる。
 * どこで顔を上げるかを選ぶのが、このゲームのほぼ全部。
 *
 * 序盤: 0.6〜0.9秒 集中して 1.9〜3.4秒 の隙
 * 100秒: 0.4〜1.2秒 集中して 0.8〜1.4秒 の隙
 * 鹿は 3.2〜5.2秒 見えているので、隙ごとに顔を上げれば必ず気づける。
 */
export function dirtyRun(t: number): { min: number; max: number } {
  const k = Math.min(1, t / 100);
  return { min: 2, max: Math.round(3 + 3 * k) };
}
export function cleanRun(t: number): { min: number; max: number } {
  const k = Math.min(1, t / 100);
  return { min: Math.round(6 - 2 * k), max: Math.round(11 - 4 * k) };
}

// ---- 大きいフン：とびこえる ----

/**
 * **大きいフンは、下を向いたままでは越えられない。とびこえる。**
 *
 * 「ふんをよけるスリルが欲しい」——もっともで、下を向いていれば
 * 自動で避かるかぎり、**失敗しうる瞬間がどこにも無い**。
 * スリルは「いま失敗するかもしれない」からしか出ない。
 *
 * ただし操作は増やさない。一度「押し直したら跨げる」を作ってみたが、
 * 押し直す＝一度離す＝顔が上がる、で視線と喧嘩したうえ、
 * **テクニックが要るゲーム**に逆戻りしていた。そこは捨てたところだった。
 *
 * かわりに理屈を使う。とぶには助走が要る。うつむいた ちょこちょこ歩きでは
 * 跳べない。だから大きいフンは**顔を上げているあいだにしか越えられない**。
 *
 * ここに山があるのは、**見るのと越えるのが逆向きだから**。
 *   足元は下を向かないと見えない → いつ来るかは、下を向いて覚える
 *   越えるには顔を上げる         → 跳ぶ瞬間、足元はもう見えない
 * 覚えて、目を切って、跳ぶ。これがフンを避けることそのもののスリルになる。
 */

/** 汚れた区間に大きいフンを混ぜる確率。 */
export function bigChance(t: number): number {
  return 0.45 + 0.4 * Math.min(1, t / 100);
}

/**
 * 大きいフンの**手前**を、これだけのマス空ける。
 * 小さいフンを避けている姿勢から顔を上げるまでの猶予がここ。
 * 3マス = 90px。うつむいて歩いていればいちばん速いときでも 0.94秒あり、
 * T_MIN を割らない。空いたマスがそのまま「来るぞ」の合図にもなる。
 */
export const BIG_GAP = 3;
/** 大きいフンを置くために、汚れた区間をこのマス数まで伸ばす。 */
export const BIG_RUN_MIN = 6;
/** とびこえたときの点。危険に見合うだけ出す。 */
export const JUMP_SCORE = 90;
/** とんでいる時間[s]。足が地面から離れている絵を出すのに使う。 */
export const HOP_TIME = 0.34;

/** 同じ側で続けて出すときの最小の間隔[s]。これ以上詰めると避けようがない。 */
export const MIN_GAP = 0.42;

/**
 * **フンと鹿が届く時刻を、これだけ離す[s]。**
 *
 * ここが抜けていて、上手く見ているボットが9秒で終わっていた。
 * ふたつの流れ（フンと鹿）はそれぞれ別のタイマーで出していたので、
 * **たまたま同時に届く**ことが年中起きる。両方は見られないので必ず食う。
 * つまり「避けようのない場面」が、意図せず山ほど生まれていた。
 *
 * 意図した重なり（clashChance）だけが避けようのない場面であるべきで、
 * それ以外は必ず切り替える余地を残す。0.55秒 は反応時間 0.45秒 に
 * 指を動かすぶんを足した値。
 */
export const SEPARATION = 0.55;

/**
 * フンと鹿を**続けざまに**出す確率。ここがこのゲームの山場。
 *
 * 鹿のほうが速く着くので、実測で **0.4秒差の二連**になる。
 * 落ち着いていれば両方さばけるが、たいていはどちらかを食う。
 *
 * 最初は「避けようのない場面」にするつもりで書いたが、
 * 走らせてみたら避けられた——そしてそのほうが良かった。
 * 完全に詰んだ場面は、優しいようで**ただの理不尽**になる。
 * 「際どいが、間に合う」なら、食っても自分のせいだと納得でき、
 * さばけたときは気持ちがいい。0.4秒はその境目。
 *
 * どちらかを食うなら**フンのほうが軽い**（TRIP_POOP < TRIP_DEER）。
 * つまり迷ったら前を見るのが正解で、
 * 「下ばっか見てると（鹿にぶつかる）」がそのまま最適手になっている。
 */
export function clashChance(t: number): number {
  if (t < INTRO_TIME) return 0;
  return Math.min(0.26, 0.03 + (t - INTRO_TIME) / 300);
}

/**
 * 重ねて出すときの、届く時刻の差[s]。**鹿が先、フンが後。**
 *
 * ここが 0.20〜0.33秒 しかなく、「どうにもならない」場面になっていた。
 * 反応時間の下限が 0.45秒 で、しかも**切り替えて戻すので2回**要る。
 * 間に合うはずがなかった。
 *
 * 0.75秒 なら、見てから前→下と動かせる。際どいが、間に合う。
 * 鹿を先に出すのは、**重い方（鹿）を先に片づけさせる**ため。
 */
export const CLASH_GAP = 0.75;

