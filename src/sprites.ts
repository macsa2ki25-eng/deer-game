/**
 * 木。円を計算で描く。26×30まで大きくなると手描きの文字列では管理しきれない。
 * 上が明るく下が暗い球体にして、真上から見た木立に見せる。
 * まだら模様は毎回同じ（決定的）にしてある——見た目のブレでバグを疑わずに済むため。
 */
function makeTree(w: number, h: number): string[] {
  const cx = (w - 1) / 2;
  const cy = (w - 1) / 2;
  const r = w / 2 - 0.5;
  const dapple = (x: number, y: number) => {
    const n = Math.sin(x * 12.9898 + y * 78.233) * 43758.5453;
    return n - Math.floor(n);
  };
  const rows: string[] = [];
  for (let y = 0; y < h; y++) {
    let row = "";
    for (let x = 0; x < w; x++) {
      // 幹。葉の下から出て、根元にいくほど暗い。
      if (y > cy + r - 3 && Math.abs(x - cx) <= 1.5) {
        row += y >= h - 2 ? "1" : y >= h - 6 ? "2" : "3";
        continue;
      }
      const d = Math.hypot(x - cx, y - cy) / r;
      if (d > 1) {
        row += ".";
        continue;
      }
      if (d > 0.92) {
        row += "s"; // いちばん外は暗く落として、砂利の上でも輪郭が消えない
        continue;
      }
      if (d > 0.8) {
        row += "7";
        continue;
      }
      // 光は左上から。そこにまだらを乗せて、のっぺりした緑の玉にしない。
      const lit = Math.hypot(x - cx + 3.5, y - cy + 3.5) / r;
      const t = dapple(x, y);
      let c = lit < 0.5 ? "9" : "8";
      if (t > 0.74) c = c === "8" ? "9" : "6";
      else if (t < 0.16) c = c === "9" ? "8" : "7";
      row += c;
    }
    rows.push(row);
  }
  return rows;
}

