export type Sprite = HTMLCanvasElement;

function bake(rows: string[]): Sprite {
  const w = rows[0].length;
  const h = rows.length;
  const c = document.createElement("canvas");
  c.width = w;
  c.height = h;
  const x = c.getContext("2d")!;
  const img = x.createImageData(w, h);
  for (let y = 0; y < h; y++) {
    if (rows[y].length !== w) {
      throw new Error(`sprite row ${y} is ${rows[y].length} wide, expected ${w}`);
    }
    for (let i = 0; i < w; i++) {
      const col = PAL[rows[y][i]];
      const o = (y * w + i) * 4;
      if (!col) {
        img.data[o + 3] = 0;
        continue;
      }
      img.data[o] = parseInt(col.slice(1, 3), 16);
      img.data[o + 1] = parseInt(col.slice(3, 5), 16);
      img.data[o + 2] = parseInt(col.slice(5, 7), 16);
      img.data[o + 3] = 255;
    }
  }
  x.putImageData(img, 0, 0);
  return c;
}

/**
 * 縮める。**遠くのものを描くのに使う。**
 *
 * 毎フレーム drawImage で拡大縮小すると、輪郭が半端な位置に落ちて溶ける。
 * 先に縮めて焼いておけば、どの距離でもドットのまま出る。
 *
 * 単純な間引きだと、縮めたときに輪郭がやせて silhouette が崩れる。
 * **元の区画のうち中身が4割以上あれば、そこでいちばん多い色を採る**——
 * こうすると小さくしても「鹿の形」が残る。
 */
function shrink(rows: string[], k: number): string[] {
  const sw = rows[0].length;
  const sh = rows.length;
  const w = Math.max(1, Math.round(sw * k));
  const h = Math.max(1, Math.round(sh * k));
  const out: string[] = [];
  for (let y = 0; y < h; y++) {
    let line = "";
    for (let x = 0; x < w; x++) {
      const x0 = Math.floor((x * sw) / w);
      const x1 = Math.max(x0 + 1, Math.floor(((x + 1) * sw) / w));
      const y0 = Math.floor((y * sh) / h);
      const y1 = Math.max(y0 + 1, Math.floor(((y + 1) * sh) / h));
      const count: Record<string, number> = {};
      let filled = 0;
      let total = 0;
      for (let sy = y0; sy < Math.min(sh, y1); sy++) {
        for (let sx = x0; sx < Math.min(sw, x1); sx++) {
          const c = rows[sy][sx];
          total++;
          if (c === ".") continue;
          filled++;
          count[c] = (count[c] ?? 0) + 1;
        }
      }
      if (filled * 2.5 < total) {
        line += ".";
        continue;
      }
      let best = ".";
      let n = 0;
      for (const c of Object.keys(count)) {
        if (count[c] > n) {
          best = c;
          n = count[c];
        }
      }
      line += best;
    }
    out.push(line);
  }
  return out;
}

