/**
 * 木。前方の帯を埋める役。
 *
 * **背を高くしてある。** 低い木にしたら上帯の3/4が水色の空になり、
 * 「何も起きない場所」が画面の半分を占めた。速さも伝わらない。
 * 奈良公園は実際に杉と松の高い木が参道を挟んでいるので、絵としても合う。
 */
function makeTree(w: number, h: number): string[] {
  const cx = (w - 1) / 2;
  const cy = (w - 1) / 2;
  const r = w / 2 - 0.5;
  const dapple = (x: number, y: number) => {
    const n = Math.sin(x * 12.9898 + y * 78.233) * 43758.5453;
    return n - Math.floor(n);
  };
  const rows: string[] = [];
  for (let y = 0; y < h; y++) {
    let row = "";
    for (let x = 0; x < w; x++) {
      if (y > cy + r - 3 && Math.abs(x - cx) <= 1.5) {
        // 幹は木の色で。**フンと同じ色を使わない**——
        // 「顔を上げているあいだ足元は見えない」を画素で数える検査が、
        // 幹をフンと取り違えてしまう。色そのものが検査の言葉になっている。
        row += y >= h - 2 ? "1" : y >= h - 6 ? "n" : "i";
        continue;
      }
      const d = Math.hypot(x - cx, y - cy) / r;
      if (d > 1) {
        row += ".";
        continue;
      }
      const n = dapple(x, y);
      row += d > 0.86 ? "s" : d > 0.62 ? (n < 0.4 ? "7" : "8") : n < 0.34 ? "9" : "8";
    }
    rows.push(row);
  }
  return rows;
}

/**
 * 焼いたもの。遠くのものは3段階に縮めて持つ。
 * `pick(set, z)` で距離に合う1枚を選ぶ。
 */
function sizes(rows: string[]): Sprite[] {
  return [bake(rows), bake(shrink(rows, 0.62)), bake(shrink(rows, 0.36))];
}

