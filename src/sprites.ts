function glyphSet(col: string): Record<string, Sprite> {
  const out: Record<string, Sprite> = {};
  for (const [k, rows] of Object.entries(GLYPHS)) {
    out[k] = bake(rows.map((r) => r.replace(/1/g, col)));
  }
  return out;
}

