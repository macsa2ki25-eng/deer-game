/**
 * 距離に合う1枚を選ぶ。**段でしか変わらない**ので、
 * 近づいてくるときに輪郭がじわじわ溶けることがない。
 */
export function pick(set: Sprite[], scale: number): Sprite {
  return scale > 0.62 ? set[0] : scale > 0.34 ? set[1] : set[2];
}


